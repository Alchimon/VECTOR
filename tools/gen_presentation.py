def _slide():
    return prs.slides.add_slide(BLANK)


def _rect(slide, x, y, w, h, color, line=False):
    from pptx.enum.shapes import MSO_SHAPE
    sh = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, x, y, w, h)
    sh.fill.solid()
    sh.fill.fore_color.rgb = color
    if not line:
        sh.line.fill.background()
    else:
        sh.line.color.rgb = SOFT
        sh.line.width = Pt(1)
    sh.shadow.inherit = False
    return sh


def _text(slide, x, y, w, h, runs, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, space_after=6):
    """runs: список абзацев; каждый абзац — список (текст, размер, цвет, жирный)."""
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    first = True
    for para in runs:
        p = tf.paragraphs[0] if first else tf.add_paragraph()
        first = False
        p.alignment = align
        p.space_after = Pt(space_after)
        for text, size, color, bold in para:
            r = p.add_run()
            r.text = text
            r.font.size = Pt(size)
            r.font.color.rgb = color
            r.font.bold = bold
            r.font.name = "Segoe UI"
    return box


def _pic_fit(slide, path, x, y, w, h, border=True):
    """Вставить скриншот, вписав в рамку (без искажения), с тонкой рамкой."""
    path = str(path)
    with Image.open(path) as im:
        iw, ih = im.size
    scale = min(w / iw, h / ih)
    pw, ph = int(iw * scale), int(ih * scale)
    px = x + int((w - pw) / 2)
    py = y + int((h - ph) / 2)
    pic = slide.shapes.add_picture(path, px, py, width=pw, height=ph)
    if border:
        pic.line.color.rgb = SOFT
        pic.line.width = Pt(1.2)
    return pic


PAGE = [0]


def header(slide, title, kicker=""):
    """Шапка слайда: полоса primary + заголовок + номер."""
    PAGE[0] += 1
    _rect(slide, 0, 0, SW, Inches(0.16), PRIMARY)
    if kicker:
        _text(slide, Inches(0.55), Inches(0.28), SW - Inches(1.1), Inches(0.3),
              [[(kicker, 12, ACCENT, True)]])
        ty = Inches(0.55)
    else:
        ty = Inches(0.35)
    _text(slide, Inches(0.55), ty, SW - Inches(1.6), Inches(0.9),
          [[(title, 30, PRIMARY_DARK, True)]])
    _text(slide, SW - Inches(0.9), SH - Inches(0.45), Inches(0.6), Inches(0.3),
          [[(str(PAGE[0]), 11, MUTED, False)]], align=PP_ALIGN.RIGHT)
    _rect(slide, Inches(0.55), ty + Inches(0.62), Inches(1.1), Pt(3), ACCENT)


def bullets(slide, x, y, w, h, items, size=15, gap=8, marker_color=ACCENT):
    """items: список (жирный заголовок или None, текст) или просто текст."""
    runs = []
    for it in items:
        if isinstance(it, tuple):
            head, body = it
            runs.append([("▪ ", size, marker_color, True), (head, size, PRIMARY_DARK, True),
                         ((" — " + body) if body else "", size, TEXT, False)])
        else:
            runs.append([("▪ ", size, marker_color, True), (it, size, TEXT, False)])
    _text(slide, x, y, w, SH - y - Inches(0.4) if h is None else h, runs, space_after=gap)


def shot_slide(title, kicker, image, items, caption="", img_ratio=0.56):
    s = _slide()
    header(s, title, kicker)
    iw = Inches(13.333 * img_ratio)
    ix = SW - iw - Inches(0.45)
    iy = Inches(1.55)
    ih = SH - iy - Inches(0.75)
    _pic_fit(s, SHOTS / image, ix, iy, iw, ih)
    bullets(s, Inches(0.55), Inches(1.65), ix - Inches(0.95), None, items, size=14, gap=9)
    if caption:
        _text(s, ix, SH - Inches(0.5), iw, Inches(0.3),
              [[(caption, 10.5, MUTED, False)]], align=PP_ALIGN.CENTER)
    return s


