"""Поля запросов, которые являются секретами (пароли), и как их не сохранять.

Зачем отдельный модуль: правило нужно и серверу, и клиенту, и они должны совпадать.

* Сервер считает хэш запроса (operations.request_hash) для защиты от повторов. Если в хэш попадёт пароль, по этому
  хэшу пароль можно подобрать: SHA-256 без соли считается миллиарды раз в секунду на видеокарте, в обход медленного
  argon2. Поэтому секретные поля в хэш не входят вовсе (ни значение, ни сам ключ).
* Клиент запоминает онлайн-операцию с потерянным ответом в очереди, чтобы потом спросить сервер «выполнена ли она»
  тем же operation_id. Пароль при этом не нужен (сервер вернёт сохранённый ответ) и сохраняться не должен.

Если операция до сервера не дошла, повтор без пароля будет отклонён (пароль обязателен) — пользователь повторит её
сам. Это безопасный исход: ничего не выполняется дважды и пароль нигде не лежит.
"""
from __future__ import annotations

# Все поля с паролями во всех командах. Новое поле с секретом в команде — ОБЯЗАТЕЛЬНО добавить сюда (тест сверяет
# с каталогом команд по имени: поля «*password*»).
SECRET_FIELDS = frozenset({"password", "current_password", "new_password", "initial_password", "temporary_password",
                           "sign_password"})

# Команды, которые ДО этого исправления записывали хэш запроса с паролем внутри — их старые записи operations
# зачищает `vector-server redact-secrets`.
LEGACY_SECRET_COMMANDS = ("account.change_password", "admin.create_user", "admin.reset_password")


def without_secrets(payload: dict) -> dict:
    """Копия payload без секретных полей (для хэша запроса и для локального сохранения операции)."""
    return {k: v for k, v in payload.items() if k not in SECRET_FIELDS}
