def _norm(text: str) -> str:
    """Текст элемента без счётчиков и хвостов: «Задачи (3)» → «Задачи», «Открыто: 2» → «Открыто»."""
    t = re.sub(r"\s+", " ", (text or "").strip())
    t = re.sub(r"\s*\(\d+\)$", "", t)          # «Мои операции (1)»
    t = re.sub(r"\s*\($", "", t)               # «Позиции (» — заголовок, к которому QML дописывает число
    t = re.sub(r":\s*[\d\s.,]*$", "", t)       # «Открыто: 2»
    return t.strip()


@lru_cache(maxsize=4096)
def tip(text: str) -> str:
    """Подсказка для элемента с текстом ``text``: пояснение (если есть) и расшифровка сокращений.

    Пустая строка — подсказывать нечего (обычное слово без сокращений и без пояснения).
    """
    t = _norm(text)
    if not t:
        return ""
    base = HINTS.get(t, "")
    lines = [base] if base else []
    for a in abbreviations_in(t + " " + base):
        e = expand(a)
        if e and e not in lines:
            lines.append(e)
    return "\n".join(lines)


def has_hint(text: str) -> bool:
    """Есть ли у элемента собственное пояснение (а не только расшифровка сокращений)."""
    return _norm(text) in HINTS


def glossary_rows() -> list[dict]:
    """Строки справочника «Сокращения» для окна справки и руководства: по алфавиту, без повторов полных форм."""
    rows, seen = [], set()
    for a, (f, n) in GLOSSARY.items():
        if a.lower() in seen:            # «Ед.» и «ЕД.», «корр.» и «Корр.» — одна строка справочника
            continue
        seen.add(a.lower())
        rows.append({"abbr": a, "full": f, "note": n})
    # Сначала русские сокращения (их большинство), затем латинские; внутри — по алфавиту.
    rows.sort(key=lambda r: (r["abbr"][0].isascii(), r["abbr"].lower().strip(".")))
    return rows
